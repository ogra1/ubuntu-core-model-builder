/// `GET {store}/api/v2/tokens/whoami` with the persisted credentials.
///
/// Blocking (bounded by the HTTP timeout) — call from a background isolate
/// or via an `async` FFI binding in Dart. Returns JSON: `{"name": "..."}`.
#[no_mangle]
pub extern "C" fn auth_whoami(handle: *mut AuthRuntimeHandle, out_err: *mut *mut c_char) -> *mut c_char {
    let outcome: std::result::Result<std::result::Result<String, AuthenticationError>, String> = guard_panic(|| {
        let rt = runtime_static(handle)?;
        // Runs on the shared multithreaded runtime (spawn + oneshot), so
        // this call is safe from the Flutter UI thread.
        // Returns the full account: {id, email, username, display_name,
        // permissions, channels, expires}.
        let info = runtime::block_on(rt.whoami())?;
        serde_json::to_string(&info)
            .map_err(|e| AuthenticationError::InvalidResponse(format!("encode whoami: {e}")))
    });
    match outcome {
        Ok(Ok(s)) => to_cstring(&s),
        Ok(Err(e)) => {
            unsafe { set_out_err(out_err, &error_json(&e)) };
            std::ptr::null_mut()
        }
        Err(json) => {
            unsafe { set_out_err(out_err, &json) };
            std::ptr::null_mut()
        }
    }
}

